package ch02;

public class DataType3 {
    public static void main(String[] args) {
        // 기본자료형(실수형) - float(4byte) , double(8byte)
        float fBox1 = 0.5f; // 실수형의 기본 자료형은 double이기 때문에 f를 붙여서 float라고 명시해줌.
        // 접미사를 사용해서 자바(컴파일러)에게 0.5는 double이 아니라 float타입이라고 명시.

        // 실수형 자료에서 기본 연산의 단위는 double.
        double dBox1 = 0.123;
        double dBox2 = 0.5;

    } // end of main
} // end of class
